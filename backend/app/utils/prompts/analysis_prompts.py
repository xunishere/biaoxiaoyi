"""标书解析相关提示词。"""

from typing import Dict, List


def build_analysis_messages(
    file_content: str, analysis_type: str
) -> List[Dict[str, str]]:
    """构建文档分析消息。"""
    system_prompt = """你是一名专业的招标文件分析助手。请严格基于用户提供的招标文件原文完成分析任务。

通用要求：
1. 保持提取信息的全面性和准确性，尽量使用原文内容，不要自行编造
2. 只输出最终分析结果，不要输出额外说明、过程、提示语或客套话
3. 如果文档内容不足以支持某项结论，应明确说明原文未提及，不要凭空补充
"""

    file_prompt = f"""以下是完整招标文件全文，请先完整阅读，并仅基于原文完成后续任务：

{file_content}"""

    if analysis_type == "overview":
        task_prompt = """任务：提取并总结项目概述信息。

请重点关注以下方面：
1. 项目名称和基本信息
2. 项目背景和目的
3. 项目规模和预算
4. 项目时间安排
5. 项目要实施的具体内容
6. 主要技术特点
7. 其他关键要求

工作要求：
1. 保持提取信息的全面性和准确性，尽量使用原文内容，不要自己编写
2. 只关注与项目实施有关的内容，不提取商务信息
3. 直接返回整理好的项目概述，除此之外不返回任何其他内容
"""
    elif analysis_type == "requirements":
        task_prompt = """任务：提取技术评分要求。

你是一名专业的招标文件分析师，擅长从复杂的招标文档中高效提取“技术评分项”相关内容。请严格按照以下步骤和规则执行任务：
### 1. 目标定位
- 重点识别文档中与“技术评分”、“评标方法”、“评分标准”、“技术参数”、“技术要求”、“技术方案”、“技术部分”或“评审要素”相关的章节（如“第X章 评标方法”或“附件X：技术评分表”）。
- 一定不要提取商务、价格、资质等与技术类评分项无关的条目。
### 2. 提取内容要求
对每一项技术评分项，按以下结构化格式输出（若信息缺失，标注“未提及”），如果评分项不够明确，你需要根据上下文分析并也整理成如下格式：
【评分项名称】：<原文描述，保留专业术语>
【权重/分值】：<具体分值或占比，如“30分”或“40%”>
【评分标准】：<详细规则，如“≥95%得满分，每低1%扣0.5分”>
【数据来源】：<文档中的位置，如“第5.2.3条”或“附件3-表2”>

### 3. 处理规则
- 模糊表述：有些招标文件格式不是很标准，没有明确的“技术评分表”，但一定都会有“技术评分”相关内容，请根据上下文判断评分项。
- 表格处理：若评分项以表格形式呈现，按行提取，并标注“[表格数据]”。
- 分层结构：若存在二级评分项（如“技术方案→子项1、子项2”），用缩进或编号体现层级关系。
- 单位统一：将所有分值统一为“分”或“%”，并注明原文单位。

### 4. 验证步骤
提取完成后，执行以下自检：
- [ ] 所有技术评分项是否覆盖（无遗漏）？
- [ ] 是否错误提取商务、价格、资质等与技术类评分项无关的条目？
- [ ] 权重总和是否与文档声明的技术分总分一致（如“技术部分共60分”）？

直接返回提取结果，除此之外不输出任何其他内容
"""
    elif analysis_type == "commercial":
        task_prompt = """任务：提取商务/价格评分要求。

你是一名专业的招标文件分析师，擅长从复杂的招标文档中高效提取"商务评分"和"价格评分"相关内容。请严格按照以下步骤和规则执行任务：
### 1. 目标定位
- 重点识别文档中与"商务评分"、"价格评分"、"报价得分"、"商务评审"、"价格评审"、"资质要求"、"业绩要求"相关的章节。
- 一定不要提取技术方案、技术参数、技术评分等技术类评分项。

### 2. 提取内容要求
对每一项商务/价格评分项，按以下结构化格式输出（若信息缺失，标注"未提及"）：
【评分项名称】：<原文描述，保留专业术语>
【权重/分值】：<具体分值或占比，如"20分"或"30%">
【评分标准】：<详细规则，如"有效最低价法"、"每提供1个同类项目得2分，最多10分">
【数据来源】：<文档中的位置，如"第3.2条"或"附件2-表1">

### 3. 重点关注类别
- 报价评分：投标报价、基准价计算规则、价格分计算公式
- 企业资质：注册资金、ISO认证、行业许可证、信用评级
- 类似业绩：同类项目数量、合同金额门槛、项目完成时间要求
- 人员资质：项目经理证书、技术负责人职称、社保要求
- 履约信誉：违约记录、诉讼记录、获奖情况
- 其他商务：售后服务、质保期、付款方式等评分

### 4. 处理规则
- 模糊表述：根据上下文判断评分项归属，不要遗漏
- 表格处理：若评分项以表格形式呈现，按行提取，并标注"[表格数据]"
- 分层结构：若存在二级评分项，用缩进或编号体现层级关系
- 单位统一：将所有分值统一为"分"或"%"，并注明原文单位

### 5. 验证步骤
提取完成后，执行以下自检：
- [ ] 所有商务/价格评分项是否覆盖（无遗漏）？
- [ ] 是否错误提取了技术类评分项？
- [ ] 权重总和是否与文档声明的商务分/价格分总分一致？

直接返回提取结果，除此之外不输出任何其他内容
"""
    elif analysis_type == "framework":
        task_prompt = """任务：提取招标文件要求的投标文件框架结构。

你是一名专业的招标文件分析师。请从招标文件全文中，找出「投标文件应包含的内容/章节/组成部分」的规定。

### 1. 目标定位
- 这些内容通常出现在"投标文件的编制"、"投标文件组成"、"投标文件应包含"、"商务技术资料"、"评标标准相应的资料"、"投标文件格式要求"等章节
- 关键特征：以分部分/分章节/编号列表的形式，规定投标人必须提交哪些内容
- 务必区分：这是"投标文件框架"（规定投标文件该有哪些章节），不是"评分标准"（规定怎么打分）

### 2. 提取内容要求
按原文的一二级结构提取，保留编号层级：
- 一级标题（如"资信部分"、"技术部分"）
- 二级条目（如"单位介绍"、"需求理解"、"总体设计方案"）
- 若原文有编号（1. 2. 3. 或（一）（二）等），完整保留
- 若原文某些条目标注"（如有）"，保留该标注

### 3. 输出格式
按以下格式输出：

【一级】<一级标题>
  - 二级条目1
  - 二级条目2
  ...

例如：
【一级】资信部分
  - 1. 单位介绍
  - 2. 类似项目业绩证明材料（如有）
  - 3. 资格、资质、获得的荣誉等证明文件（如有）
  - 4. 商务偏离表
  - 5. 投标人认为需要提供的其他资料
【一级】技术部分
  - 1. 项目需求的理解
  - 2. 总体设计方案
  ...

### 4. 验证步骤
- [ ] 是否已覆盖原文规定的所有一级部分？
- [ ] 每个一级下的二级条目是否完整？
- [ ] 是否正确区分了"投标文件框架"与"评分标准"？

直接返回提取结果，除此之外不输出任何其他内容
"""

    return [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": file_prompt},
        {"role": "user", "content": task_prompt},
    ]
